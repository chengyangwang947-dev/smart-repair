-- 练习四：智能报修小助手 数据库结构
-- 在 Supabase SQL 编辑器中逐段执行；本段可整体运行

-- 报修单
create table if not exists repairs (
  id bigint generated by default as identity primary key,
  reporter_name text not null,
  office_area text not null,
  device text not null,
  description text not null,
  status text not null default 'pending',   -- pending 待处理 / processing 处理中 / done 已完成
  group_id text not null default 'group-01',
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

create index if not exists repairs_group_idx on repairs (group_id, created_at desc);

-- AI 排查建议（跟随报修单保存）
create table if not exists repair_suggestions (
  id bigint generated by default as identity primary key,
  repair_id bigint not null references repairs(id) on delete cascade,
  content text not null,
  created_at timestamptz default now()
);

create index if not exists suggestions_repair_idx on repair_suggestions (repair_id);

-- 启用 RLS
alter table repairs enable row level security;
alter table repair_suggestions enable row level security;

-- 练习环境说明：服务端接口持有 anon key 访问数据库；
-- “未登录不可读写”由应用接口层（api/_lib/auth.js）校验会话完成。
drop policy if exists anon_all_repairs on repairs;
create policy anon_all_repairs on repairs for all to anon using (true) with check (true);

drop policy if exists anon_all_suggestions on repair_suggestions;
create policy anon_all_suggestions on repair_suggestions for all to anon using (true) with check (true);
